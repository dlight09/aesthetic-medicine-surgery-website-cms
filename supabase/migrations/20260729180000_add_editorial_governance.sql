alter table public.blog_posts
  add column if not exists reviewer_name text null,
  add column if not exists reviewed_at timestamptz null;
alter table public.interventions
  add column if not exists reviewer_name text null,
  add column if not exists reviewed_at timestamptz null;
create table if not exists public.content_revisions (
  id bigint generated by default as identity primary key,
  content_type text not null,
  record_id uuid not null,
  slug text not null,
  snapshot jsonb not null,
  created_at timestamptz not null default now(),
  constraint content_revisions_type_check check (content_type in ('blog_post', 'intervention'))
);
create index if not exists content_revisions_record_idx
  on public.content_revisions(content_type, record_id, created_at desc);
alter table public.content_revisions enable row level security;
create or replace function public.snapshot_content_revision()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.content_revisions (content_type, record_id, slug, snapshot)
  values (
    case TG_TABLE_NAME
      when 'blog_posts' then 'blog_post'
      when 'interventions' then 'intervention'
    end,
    old.id,
    old.slug,
    to_jsonb(old)
  );
  if TG_OP = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;
revoke execute on function public.snapshot_content_revision() from public, anon, authenticated;
drop trigger if exists trg_blog_posts_revision on public.blog_posts;
create trigger trg_blog_posts_revision
before update or delete on public.blog_posts
for each row execute function public.snapshot_content_revision();
drop trigger if exists trg_interventions_revision on public.interventions;
create trigger trg_interventions_revision
before update or delete on public.interventions
for each row execute function public.snapshot_content_revision();
revoke all on public.content_revisions from anon, authenticated;
alter table public.blog_posts
  drop constraint if exists blog_posts_publication_review_check;
alter table public.blog_posts
  add constraint blog_posts_publication_review_check
  check (status <> 'publie' or (nullif(btrim(reviewer_name), '') is not null and reviewed_at is not null)) not valid;
alter table public.interventions
  drop constraint if exists interventions_publication_review_check;
alter table public.interventions
  add constraint interventions_publication_review_check
  check (status <> 'publie' or (nullif(btrim(reviewer_name), '') is not null and reviewed_at is not null)) not valid;
